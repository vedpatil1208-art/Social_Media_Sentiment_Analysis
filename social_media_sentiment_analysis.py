from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import train_test_split

# Remove empty processed text
combined = combined.dropna(subset=["processed_text", "sentiment"])

# Keep only valid sentiment labels
combined = combined[
    combined["sentiment"].isin([-1, 0, 1])
]

X = combined["processed_text"]
y = combined["sentiment"]

print("Total records:", len(combined))
print("Sentiment classes:", y.unique())

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

tfidf = TfidfVectorizer(
    max_features=10000,
    ngram_range=(1, 2)
)

X_train_tfidf = tfidf.fit_transform(X_train)
X_test_tfidf = tfidf.transform(X_test)

print("Training matrix:", X_train_tfidf.shape)
print("Testing matrix:", X_test_tfidf.shape)

from sklearn.naive_bayes import MultinomialNB
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

nb_model = MultinomialNB()

nb_model.fit(X_train_tfidf, y_train)

print("Naive Bayes model trained successfully!")

nb_predictions = nb_model.predict(X_test_tfidf)

print("First 10 actual labels:")
print(y_test[:10].values)

print("\nFirst 10 predicted labels:")
print(nb_predictions[:10])

nb_accuracy = accuracy_score(y_test, nb_predictions)

nb_precision = precision_score(
    y_test, nb_predictions, average="weighted"
)

nb_recall = recall_score(
    y_test, nb_predictions, average="weighted"
)

nb_f1 = f1_score(
    y_test, nb_predictions, average="weighted"
)

print("NAIVE BAYES RESULTS")
print("-------------------")
print("Accuracy:", round(nb_accuracy * 100, 2), "%")
print("Precision:", round(nb_precision, 4))
print("Recall:", round(nb_recall, 4))
print("F1 Score:", round(nb_f1, 4))

print(classification_report(
    y_test,
    nb_predictions,
    target_names=["Negative", "Neutral", "Positive"]
))

